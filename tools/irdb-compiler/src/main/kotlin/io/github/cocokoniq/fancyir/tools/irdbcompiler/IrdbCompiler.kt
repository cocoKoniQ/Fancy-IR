package io.github.cocokoniq.fancyir.tools.irdbcompiler

import io.github.cocokoniq.fancyir.core.irdb.DeviceCategory
import io.github.cocokoniq.fancyir.core.irdb.FlipperIrParser
import io.github.cocokoniq.fancyir.core.irdb.IrdbPath
import io.github.cocokoniq.fancyir.core.irdb.StarterLibrary
import io.github.cocokoniq.fancyir.core.irdb.catalog.BrandKey
import io.github.cocokoniq.fancyir.core.irdb.catalog.CatalogBundle
import io.github.cocokoniq.fancyir.core.irdb.catalog.CatalogCodeset
import io.github.cocokoniq.fancyir.core.irdb.catalog.CatalogSource
import io.github.cocokoniq.fancyir.core.irdb.catalog.FlipperCatalog
import io.github.cocokoniq.fancyir.core.irdb.smartir.SmartIr
import io.github.cocokoniq.fancyir.core.irdb.smartir.SmartIrPlatform
import java.io.File
import java.security.MessageDigest
import java.util.zip.GZIPOutputStream
import kotlin.system.exitProcess

/**
 * Compiles the bundled Layer 2 catalog (ARCHITECTURE.md §3.8) from local checkouts of
 * Flipper-IRDB and SmartIR plus our hand-written starter sets. See `generate-catalog.sh`.
 */
fun main(args: Array<String>) {
    val options = Options.parse(args) ?: exitProcess(2)
    val report = StringBuilder()
    val codesets = ArrayList<CatalogCodeset>()

    codesets += StarterLibrary.entries.map { entry ->
        FlipperCatalog.codeset(entry.resource, StarterLibrary.load(entry), rank = 1, source = CatalogSource.STARTER, license = "MIT (Fancy-IR)")
            .copy(id = "starter:${entry.id}", category = entry.category, brand = entry.brand, label = entry.label)
    }
    report.appendLine("starter: ${codesets.size} code sets")

    options.irdb?.let { root -> codesets += compileFlipper(root, options, report) }
    options.smartIr?.let { root -> codesets += compileSmartIr(root, options, report) }

    val ranked = rerank(codesets)
    val comment = buildString {
        appendLine("Generated by tools/irdb-compiler. Do not edit by hand.")
        appendLine("Licence policy: ${options.policy}. Sources and licences are recorded per code set.")
        append(report.toString().trimEnd())
    }
    val text = buildString { CatalogBundle.write(ranked.asSequence(), this, comment) }
    options.out.parentFile?.mkdirs()
    GZIPOutputStream(options.out.outputStream()).bufferedWriter().use { it.write(text) }
    val revision = MessageDigest.getInstance("SHA-256").digest(text.toByteArray()).joinToString("") { "%02x".format(it) }.take(16)
    File(options.out.parentFile, "catalog.properties").writeText(
        "revision=$revision\nformat=${CatalogBundle.FORMAT_VERSION}\ncodesets=${ranked.size}\ncommands=${ranked.sumOf { it.commands.size }}\n",
    )
    println(report)
    println("wrote ${ranked.size} code sets, ${ranked.sumOf { it.commands.size }} commands, revision $revision -> ${options.out}")
}

private fun compileFlipper(root: File, options: Options, report: StringBuilder): List<CatalogCodeset> {
    val excluded = options.irdbExclude?.readLines()?.map(String::trim)?.filter(String::isNotEmpty)?.toSet().orEmpty()
    val out = ArrayList<CatalogCodeset>()
    for (category in options.categories) {
        val byBrand = category.irdbFolders.flatMap { folder ->
            File(root, folder).walkTopDown().filter { it.isFile && it.extension.equals("ir", ignoreCase = true) }.toList()
        }.mapNotNull { file ->
            val path = file.relativeTo(root).invariantSeparatorsPath
            if (path in excluded) return@mapNotNull null
            val entry = IrdbPath.parse(path) ?: return@mapNotNull null
            Triple(BrandKey.of(entry.brand), path, file)
        }.groupBy({ it.first }, { it.second to it.third })

        val brands = byBrand.entries.sortedByDescending { it.value.size }.take(options.maxBrands)
        var families = 0
        for ((_, files) in brands) {
            val parsed = files.map { (path, file) -> path to FlipperIrParser.parse(file.readText()) }.filter { it.second.signals.isNotEmpty() }
            val ranked = FlipperCatalog.rankedCodesets(parsed, options.maxFamilies)
            families += ranked.size
            out += ranked
        }
        report.appendLine("flipper-irdb ${category.name}: ${brands.size} brands, $families code sets")
    }
    if (excluded.isNotEmpty()) report.appendLine("flipper-irdb: excluded ${excluded.size} paths that predate the CC0 relicensing")
    return out
}

private fun compileSmartIr(root: File, options: Options, report: StringBuilder): List<CatalogCodeset> {
    val out = ArrayList<CatalogCodeset>()
    val plan = listOf(
        Triple(SmartIrPlatform.CLIMATE, DeviceCategory.AIR_CONDITIONER, options.climateBrands),
        Triple(SmartIrPlatform.FAN, DeviceCategory.FAN, Int.MAX_VALUE),
        Triple(SmartIrPlatform.LIGHT, DeviceCategory.LIGHT, Int.MAX_VALUE),
    )
    for ((platform, category, maxBrands) in plan) {
        val index = SmartIr.parseIndex(File(root, "docs/${platform.docsPage}").readText())
            .filter { it.controller.contains("Broadlink", ignoreCase = true) }
            .distinctBy { it.code }
        val brands = index.groupBy { BrandKey.of(it.manufacturer) }.entries.sortedByDescending { it.value.size }.take(maxBrands)
        var count = 0
        for ((_, entries) in brands) {
            entries.mapNotNull { entry ->
                val file = File(root, "codes/${platform.folder}/${entry.code}.json").takeIf(File::isFile) ?: return@mapNotNull null
                runCatching { SmartIr.parse(file.readText(), platform, entry.code, category, rank = 1) }.getOrNull()
            }.take(options.profilesPerBrand).forEach {
                out += it
                count++
            }
        }
        report.appendLine("smartir ${platform.folder}: ${brands.size} brands, $count profiles")
    }
    return out
}

/** Ranks are per (category, brand) across sources: our verified starters, then IRDB families, then SmartIR. */
private fun rerank(codesets: List<CatalogCodeset>): List<CatalogCodeset> {
    val sourceOrder = listOf(CatalogSource.STARTER, CatalogSource.FLIPPER_IRDB, CatalogSource.SMARTIR, CatalogSource.USER)
    return codesets
        .groupBy { it.category to it.brandKey }
        .flatMap { (_, group) ->
            group.sortedWith(compareBy({ sourceOrder.indexOf(it.source) }, { it.rank }, { it.id }))
                .mapIndexed { index, set -> set.copy(rank = index + 1) }
        }
        .sortedWith(compareBy({ it.category.ordinal }, { it.brandKey }, { it.rank }))
}

private class Options(
    val irdb: File?,
    val irdbExclude: File?,
    val smartIr: File?,
    val out: File,
    val categories: List<DeviceCategory>,
    val maxBrands: Int,
    val maxFamilies: Int,
    val climateBrands: Int,
    val profilesPerBrand: Int,
) {
    val policy: String get() = if (irdbExclude != null) "Flipper-IRDB files added after the CC0 relicensing only" else "all Flipper-IRDB files"

    companion object {
        private val defaultCategories = listOf(
            DeviceCategory.TV, DeviceCategory.MONITOR, DeviceCategory.PROJECTOR, DeviceCategory.SOUNDBAR,
            DeviceCategory.AV_RECEIVER, DeviceCategory.SPEAKER, DeviceCategory.FAN, DeviceCategory.LIGHT,
            DeviceCategory.AIR_CONDITIONER, DeviceCategory.STREAMING_DEVICE,
        )

        fun parse(args: Array<String>): Options? {
            val map = args.toList().chunked(2).associate { it[0].removePrefix("--") to it.getOrElse(1) { "" } }
            val out = map["out"] ?: run {
                System.err.println(
                    "usage: --out <catalog.tsv.gz> [--irdb <Flipper-IRDB dir>] [--irdb-exclude <paths.txt>] [--smartir <SmartIR dir>]\n" +
                        "       [--categories TV,FAN,...] [--max-brands N] [--max-families N] [--climate-brands N] [--profiles-per-brand N]",
                )
                return null
            }
            return Options(
                irdb = map["irdb"]?.let(::File),
                irdbExclude = map["irdb-exclude"]?.let(::File),
                smartIr = map["smartir"]?.let(::File),
                out = File(out),
                categories = map["categories"]?.split(',')?.map { DeviceCategory.valueOf(it.trim()) } ?: defaultCategories,
                maxBrands = map["max-brands"]?.toInt() ?: Int.MAX_VALUE,
                maxFamilies = map["max-families"]?.toInt() ?: 3,
                climateBrands = map["climate-brands"]?.toInt() ?: 12,
                profilesPerBrand = map["profiles-per-brand"]?.toInt() ?: 2,
            )
        }
    }
}
